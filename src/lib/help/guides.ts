const KEYS = Object.keys(GUIDES).sort((a, b) => b.length - a.length);

/** คู่มือของหน้า (คำนำหน้าที่ยาวที่สุดที่ตรง) */
export function guideFor(pathname: string | null | undefined): Guide | null {
  const p = pathname || "";
  const key = KEYS.find((k) => (k.endsWith("/") ? p.startsWith(k) : p === k || p.startsWith(k + "/")));
  return key ? GUIDES[key] : null;
}
