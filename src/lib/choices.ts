/** ค่าที่ไม่ซ้ำ (ไม่สนช่องว่างหัวท้าย) จากรายการตั้งต้น + ข้อมูลจริง เรียงตามที่พบ */
export function mergeChoices(...lists: Array<Array<unknown> | undefined>): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const list of lists) for (const v of list || []) {
    const s = String(v ?? "").trim();
    if (s && !seen.has(s)) { seen.add(s); out.push(s); }
  }
  return out;
}
